const DICTS: Record<Lang, Record<MessageKey, string>> = { zh, en };

/** {var} 占位符插值；缺失变量时占位符原样保留 */
function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/** 按语言取文案；未知 key 原样返回（不抛错，损坏可定位） */
export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang] ?? DICTS.zh;
  const template = dict[key];
  if (typeof template !== 'string') return key;
  return interpolate(template, vars);
}

/** 系统 UI 语言 → 界面语言：zh* 一律中文，其余（含缺失/非法）英文 */
export function resolveSystemLang(navigatorLanguage?: string): Lang {
  if (typeof navigatorLanguage === 'string' && navigatorLanguage.toLowerCase().startsWith('zh')) {
    return 'zh';
  }
  return 'en';
}
